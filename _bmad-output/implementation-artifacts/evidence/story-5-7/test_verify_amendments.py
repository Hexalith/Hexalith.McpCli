    def invoke(self, callback, *, module=V):
        def verify(*_):
            callback()
            return ['fixture checked'], 'pending', False
        stdout, stderr = io.StringIO(), io.StringIO()
        with patch.object(module, 'verify', side_effect=verify), contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = module.main([])
        return code, stdout.getvalue(), stderr.getvalue()

