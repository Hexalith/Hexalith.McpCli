        parents = ['-p', parent] if parent else []
        return git('-c', 'user.name=Story 5.7 test fixture', '-c', 'user.email=fixture@example.invalid',
                   'commit-tree', tree, *parents, data=(subject + '\n').encode()).decode().strip()

