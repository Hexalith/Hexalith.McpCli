@contextlib.contextmanager
def owner_receipt(receipt):
    """Inject receipt bytes only in memory, leaving the real owner record intact."""
    read = Path.read_bytes
    def fixture(path):
        if path == HERE / 'approval.json':
            if receipt is None:
                raise FileNotFoundError('fixture approval receipt missing')
            return (json.dumps(receipt, ensure_ascii=False, indent=2) + '\n').encode()
        return read(path)
    with patch.object(Path, 'read_bytes', fixture):
        yield


