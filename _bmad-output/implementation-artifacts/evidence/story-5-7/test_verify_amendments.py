    def temporary_git(self, path):
        """Build a real isolated graph; never write to an owning repository."""
        def run(*args, data=None):
            result = subprocess.run(['git', '-C', str(path), *args], input=data, capture_output=True, check=True)
            return result.stdout
        run('init', '--quiet')
        return run

    def fixture_commit(self, git, files, parent=None, subject='test: fixture'):
        git('read-tree', '--empty')
        for name, content in files.items():
            blob = git('hash-object', '-w', '--stdin', data=content).decode().strip()
            git('update-index', '--add', '--cacheinfo', '100644', blob, name)
        tree = git('write-tree').decode().strip()
        parents = ['-p', parent] if parent else []
        return git('-c', 'user.name=Story 5.7 test fixture', '-c', 'user.email=fixture@example.invalid',
                   'commit-tree', tree, *parents, data=(subject + '\n').encode()).decode().strip()

