def invoke_main(module, args=None):
    stdout, stderr = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
        code = module.main(args or [])
    return code, stdout.getvalue(), stderr.getvalue()


def expected_process_reports(script, *, gitmodules=None, current_readmes=None):
    """Derive only the permitted drift reports from the actual baseline/current bytes."""
    with (ROOT / '.gitmodules').open('rb') as current_modules:
        modules = current_modules.read() if gitmodules is None else gitmodules
    changed_modules = modules != V.git(ROOT, 'show', V.BASELINE + ':.gitmodules')
    reports = ('reported: root .gitmodules changed since the Story 5.7 baseline; original source pins remain authoritative\n'
               if changed_modules else '')
    reports *= 2 if script == 'verify_amendments.py' else 1
    readmes = current_readmes or {}
    for repo in L.read_json(HERE / 'labels.json')['repositories']:
        owner = Path(repo['ownerCheckout'])
        data = readmes[owner] if owner in readmes else L.git(owner, 'show', 'origin/main:README.md')
        try:
            section = L.compatibility_section(data)
        except ValueError:
            section = None
        if section != L.checked_file(ROOT, repo['after']):
            reports += f'reported: {repo["name"]}: current origin/main compatibility labels differ from delivered candidate\n'
    return reports


def tearDownModule():
    """Remove only this test module's generated bytecode before packet scanning."""
    if __cached__ is None:
        return
    cached = Path(__cached__)
    cached.unlink(missing_ok=True)
    try:
        cached.parent.rmdir()
    except OSError:
        pass


